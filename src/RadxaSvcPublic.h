typedef struct _RADXA_SVC_STRUCT_HEADER
{
    UINT32 Size;
    UINT32 Version;
} RADXA_SVC_STRUCT_HEADER;

typedef struct _RADXA_SVC_INTERFACE_INFO
{
    RADXA_SVC_STRUCT_HEADER Header;
    UINT32 State;
    INT32 LastServiceStatus;
    UINT16 ServiceMajor;
    UINT16 ServiceMinor;
    UINT32 Capabilities;
    UINT32 RequiredCapabilities;
    UINT32 MissingCapabilities;
    UINT32 Reserved[2];
    UINT64 TxCount;
    UINT64 RxCount;
    UINT64 TimeoutCount;
    UINT64 BadMessageCount;
    UINT64 DroppedMessageCount;
} RADXA_SVC_INTERFACE_INFO;

typedef struct _RADXA_SVC_PING_RESULT
{
    RADXA_SVC_STRUCT_HEADER Header;
    UINT32 Pong;
    UINT16 ServiceMajor;
    UINT16 ServiceMinor;
} RADXA_SVC_PING_RESULT;

typedef struct _RADXA_SVC_VERSION_INFO
{
    RADXA_SVC_STRUCT_HEADER Header;
    UINT16 ServiceMajor;
    UINT16 ServiceMinor;
    UINT32 Capabilities;
} RADXA_SVC_VERSION_INFO;

typedef struct _RADXA_SVC_PROFILE_INFO
{
    RADXA_SVC_STRUCT_HEADER Header;
    UINT32 EffectiveProfile;
    UINT32 ServiceProfile;
    UINT32 FanControlMode;
    UINT32 Reserved;
} RADXA_SVC_PROFILE_INFO;

typedef struct _RADXA_SVC_SET_PROFILE_REQUEST
{
    RADXA_SVC_STRUCT_HEADER Header;
    UINT32 Profile;
    UINT32 Reserved;
} RADXA_SVC_SET_PROFILE_REQUEST;

typedef struct _RADXA_SVC_LOG_RESULT
{
    RADXA_SVC_STRUCT_HEADER Header;
    UINT32 BytesValid;
    UINT32 Reserved;
    UINT8 Data[RADXA_SVC_MAX_LOG_SIZE];
} RADXA_SVC_LOG_RESULT;

typedef struct _RADXA_SVC_PWM_INFO
{
    RADXA_SVC_STRUCT_HEADER Header;
    UINT32 ChannelCount;
    UINT32 SupportedMask;
    UINT32 DefaultChannel;
    UINT32 MinimumPeriodNanoseconds;
    UINT32 MaximumPeriodNanoseconds;
    UINT32 Reserved;
} RADXA_SVC_PWM_INFO;

typedef struct _RADXA_SVC_PWM_APPLY_REQUEST
{
    RADXA_SVC_STRUCT_HEADER Header;
    UINT32 Channel;
    UINT32 Enable;
    UINT32 PeriodNanoseconds;
    UINT32 DutyNanoseconds;
} RADXA_SVC_PWM_APPLY_REQUEST;

typedef struct _RADXA_SVC_PWM_STATE_REQUEST
{
    RADXA_SVC_STRUCT_HEADER Header;
    UINT32 Channel;
    UINT32 Reserved;
} RADXA_SVC_PWM_STATE_REQUEST;

typedef struct _RADXA_SVC_PWM_STATE
{
    RADXA_SVC_STRUCT_HEADER Header;
    UINT32 Channel;
    UINT32 Enabled;
    UINT32 PeriodNanoseconds;
    UINT32 DutyNanoseconds;
    UINT32 ActualPeriodNanoseconds;
    UINT32 ActualDutyNanoseconds;
    UINT32 PwmValue;
    UINT32 Reserved;
} RADXA_SVC_PWM_STATE;

typedef struct _RADXA_SVC_FAN_STATE
{
    RADXA_SVC_STRUCT_HEADER Header;
    UINT32 Profile;
    UINT32 Running;
    UINT32 Emergency;
    UINT32 CpuValid;
    UINT32 CpuStaleTicks;
    INT32 CpuTemperatureDeciCelsius;
    UINT32 GpuValid;
    UINT32 GpuStaleTicks;
    INT32 GpuTemperatureDeciCelsius;
    UINT32 CurrentDutyNanoseconds;
    UINT32 TargetDutyNanoseconds;
    UINT32 PwmChannel;
    UINT32 PwmPeriodNanoseconds;
    UINT32 LoopCount;
    UINT32 FaultCount;
    INT32 LastStatus;
    UINT32 ControlMode;
    UINT32 ManualPwm;
    UINT32 ControlFieldsValid;
    UINT32 Reserved;
} RADXA_SVC_FAN_STATE;

typedef struct _RADXA_SVC_FAN_CONTROL
{
    RADXA_SVC_STRUCT_HEADER Header;
    UINT32 ControlMode;
    UINT32 ManualPwm;
} RADXA_SVC_FAN_CONTROL;

typedef struct _RADXA_SVC_SENSOR_DESCRIPTOR
{
    UINT32 SensorId;
    UINT32 SensorType;
    CHAR Name[RADXA_SVC_SENSOR_NAME_LENGTH];
} RADXA_SVC_SENSOR_DESCRIPTOR;

typedef struct _RADXA_SVC_SENSOR_LIST
{
    RADXA_SVC_STRUCT_HEADER Header;
    UINT32 SensorCount;
    UINT32 Reserved;
    RADXA_SVC_SENSOR_DESCRIPTOR Sensors[RADXA_SVC_MAX_SENSORS];
} RADXA_SVC_SENSOR_LIST;

typedef struct _RADXA_SVC_SENSOR_READ_REQUEST
{
    RADXA_SVC_STRUCT_HEADER Header;
    UINT32 SensorId;
    UINT32 Reserved;
} RADXA_SVC_SENSOR_READ_REQUEST;

typedef struct _RADXA_SVC_SENSOR_READING
{
    RADXA_SVC_STRUCT_HEADER Header;
    UINT32 SensorId;
    UINT32 SensorType;
    UINT32 ValidMask;
    INT32 TemperatureMilliCelsius;
    INT32 VoltageMillivolts;
    UINT32 Reserved;
    INT64 CurrentMilliamps;
    INT64 PowerMicrowatts;
} RADXA_SVC_SENSOR_READING;

