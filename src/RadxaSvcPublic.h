/* Service capabilities returned by GET_SERVICE_VERSION. */
#define RADXA_SVC_CAP_PING                    0x00000001u
#define RADXA_SVC_CAP_PROFILE                 0x00000002u
#define RADXA_SVC_CAP_LOG                     0x00000004u
#define RADXA_SVC_CAP_PWM                     0x00000010u
#define RADXA_SVC_CAP_FANCTL                  0x00000020u
#define RADXA_SVC_CAP_FANCTL_CTRL             0x00000040u
#define RADXA_SVC_CAP_SENSORS                 0x00000080u
#define RADXA_SVC_CAP_EMI                     0x00000100u

#define RADXA_SVC_REQUIRED_CAPABILITIES       \
    (RADXA_SVC_CAP_PROFILE | RADXA_SVC_CAP_FANCTL | RADXA_SVC_CAP_FANCTL_CTRL)

/* RADXA_SVC_INTERFACE_INFO.State values. */
#define RADXA_SVC_STATE_UNAVAILABLE           0u
#define RADXA_SVC_STATE_GLINK_INTERFACE       1u
#define RADXA_SVC_STATE_LINK_UP               2u
#define RADXA_SVC_STATE_CHANNEL_CONNECTED     3u
#define RADXA_SVC_STATE_READY                 4u
#define RADXA_SVC_STATE_INCOMPATIBLE_VERSION  5u
#define RADXA_SVC_STATE_MISSING_CAPABILITIES  6u
